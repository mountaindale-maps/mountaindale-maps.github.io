import { expect, test } from "@playwright/test";

test("local editor saves, reloads, undoes, and refuses to publish plans", async ({ page }) => {
  await page.goto("/");
  await expect(page.locator("#local-banner")).toContainText("127.0.0.1");
  await expect(page.locator("#local-banner")).toContainText("Loopback only");
  await expect(page.locator("#calib")).toContainText("Approximate horizontal distance");
  await expect(page.locator("#calib")).toContainText("ground accuracy unverified");
  const firstDevice = page.locator("[data-device-id='045-UAP-U7O']");
  if (!(await firstDevice.count())) await page.locator("[data-members*='045-UAP-U7O']").click();
  await page.locator("[data-device-id='045-UAP-U7O']").click();
  await page.locator("#purpose-input").fill("Outdoor Wi-Fi for the recorded place group.");
  await page.locator("#save-public-details").click();
  await expect(page.locator("#public-preview")).toContainText("Outdoor Wi-Fi for the recorded place group.");
  await expect(page.locator("#public-preview")).toContainText("source record is unchanged");
  const previewText = (await page.locator("#public-preview .device-story").innerText()).replace(/\s+/g, " ").trim();
  await page.locator("#review-export").click();
  await page.locator("[data-export-device='045-UAP-U7O']").check();
  await page.locator("#confirm-review").check();
  await page.locator("#validate-export").click();
  await expect(page.locator("#export-result")).toContainText("Valid public snapshot");
  const previewSnapshot = await page.locator("#download-snapshot").getAttribute("data-snapshot");
  const viewer = await page.context().newPage();
  await viewer.route("**/network/data/asbuilt_public.json", (route) => route.fulfill({
    status: 200,
    contentType: "application/json",
    body: previewSnapshot,
  }));
  await viewer.goto("http://127.0.0.1:8765/network/");
  await viewer.locator("#q").fill("045-UAP-U7O");
  await viewer.locator("[data-result='045-UAP-U7O']").click();
  const viewedText = (await viewer.locator("#detail .device-story").innerText()).replace(/\s+/g, " ").trim();
  expect(viewedText).toBe(previewText);
  await viewer.close();
  await page.locator("#export-dialog").getByRole("button", { name: "Close" }).click();
  await page.locator("#undo").click();
  await expect(page.locator("#public-preview")).not.toContainText("Outdoor Wi-Fi for the recorded place group.");
  const health = await page.request.get("/api/health");
  const body = await health.json();
  expect(body.host).toBe("127.0.0.1");
  expect(body.dataDir).not.toContain("/network");

  await page.locator("#mode-notes").click();
  await page.locator("#note-text").fill("Move the pavilion AP after survey");
  await page.locator("#add-note").click();
  await expect(page.locator(".note-item")).toContainText("Move the pavilion AP after survey");
  await page.locator("#undo").click();
  await expect(page.locator(".note-item")).toHaveCount(0);
  await page.locator("#redo").click();
  await expect(page.locator(".note-item")).toContainText("Move the pavilion AP after survey");
  await page.locator("#save").click();
  await expect(page.locator("#save-state")).toContainText("Saved locally");
  await page.reload();
  await page.locator("#mode-notes").click();
  await expect(page.locator(".note-item")).toContainText("Move the pavilion AP after survey");

  await page.locator("#mode-plan").click();
  await page.locator("#planned-id").fill("PLAN-SHED-AP");
  await page.locator("#add-planned").click();
  await expect(page.locator(".planned-item")).toContainText("PLAN-SHED-AP");
  await page.locator("#review-export").click();
  await expect(page.locator("#excluded-plans")).toContainText("PLAN-SHED-AP");
  const download = page.locator("#download-snapshot");
  await expect(download).toBeDisabled();
  let downloaded = false;
  page.once("download", () => { downloaded = true; });
  await download.click({ force: true });
  expect(downloaded).toBe(false);
  await page.locator("#confirm-review").check();
  await expect(download).toBeDisabled();
  await page.locator("#confirm-review").uncheck();
  await page.locator("#validate-export").click();
  await expect(page.locator("#export-result")).toContainText("explicit reviewed selection");
  await expect(download).toBeDisabled();
  await page.locator("#confirm-review").check();
  await page.locator("#validate-export").click();
  await expect(page.locator("#export-result")).toContainText("Valid public snapshot");
  await expect(download).toBeEnabled();
  const snapshot = await download.getAttribute("data-snapshot");
  expect(snapshot).not.toContain("PLAN-SHED-AP");
  expect(snapshot).not.toContain("Move the pavilion AP");
  expect(snapshot).toContain("0000-MD-UDM-Pro-2");
  await page.locator("#confirm-review").uncheck();
  await expect(download).toBeDisabled();
  await expect(download).not.toHaveAttribute("data-snapshot");
  await page.locator("#confirm-review").check();
  await expect(download).toBeDisabled();
  await page.locator("#validate-export").click();
  await expect(download).toBeEnabled();
  const saved = page.waitForEvent("download");
  await download.click();
  expect((await saved).suggestedFilename()).toBe("mountaindale-public-snapshot.json");
  await page.getByRole("button", { name: "Close" }).click();

  await page.route("**/api/export", async (route) => {
    await new Promise((resolve) => setTimeout(resolve, 500));
    await route.continue();
  });
  await page.locator("#review-export").click();
  await page.locator("#confirm-review").check();
  await page.locator("#validate-export").click();
  await page.locator("#confirm-review").uncheck();
  await page.waitForTimeout(800);
  await expect(page.locator("#download-snapshot")).toBeDisabled();
  await expect(page.locator("#export-result")).not.toContainText("Valid public snapshot");
  await page.unroute("**/api/export");
  await page.getByRole("button", { name: "Close" }).click();

  await page.locator("#modes [data-mode='move']").click();
  const moved = page.locator("[data-device-id='045-UAP-U7O']");
  if (!(await moved.count())) await page.locator("[data-members*='045-UAP-U7O']").click();
  await page.locator("[data-device-id='045-UAP-U7O']").click();
  await page.locator("#lon-input").fill("-104.94");
  await page.locator("#apply-coords").click();
  await page.locator("#review-export").click();
  await page.locator("#confirm-review").check();
  await page.locator("[data-export-device='045-UAP-U7O']").check();
  await page.locator("#validate-export").click();
  await expect(page.locator("#export-result")).toContainText("Valid public snapshot");
  await expect(page.locator("#download-snapshot")).toBeEnabled();
  await page.locator("[data-export-device='045-UAP-U7O']").uncheck();
  await expect(page.locator("#download-snapshot")).toBeDisabled();
  await expect(page.locator("#download-snapshot")).not.toHaveAttribute("data-snapshot");
  await expect(page.locator("#export-result")).toContainText("Selection changed");
  await page.getByRole("button", { name: "Close" }).click();
  await page.locator("#modes [data-mode='group']").click();
  await page.locator("#ungroup-device").click();
  await page.locator("#undo").click();

  await page.locator("#modes [data-mode='path']").click();
  const direct = page.locator("[data-device-id='098-UAP-M']");
  if (!(await direct.count())) await page.locator("[data-members*='098-UAP-M']").click();
  await page.locator("[data-device-id='098-UAP-M']").click();
  await page.getByRole("button", { name: "lnk:NanoSwitch>098-UAP-M" }).click();
  await page.locator("#segment-rise-0").fill("3");
  await page.locator("#segment-slope-0").fill("4");
  await page.getByRole("button", { name: "Apply allowances" }).click();
  await expect(page.locator(".segment-row").first()).toContainText("Vertical drop added 3.00 m");
  await expect(page.locator(".segment-row").first()).toContainText("Slope rise hypotenuse 4.00 m");
  await expect(page.locator(".distance-total").first()).toContainText("ground accuracy unverified");
});
